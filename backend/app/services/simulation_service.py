import uuid
import json
import random
from datetime import datetime
from typing import List, Optional, Dict, Any
from sqlalchemy.orm import Session
from backend.app.models.network import DeviceModel, EventLogModel, HospitalModel
from backend.app.schemas.network import SimulationFlow, SimulationHop, SeverityLevel
from backend.app.services.sync_service import manager

class SimulationService:
    # Router mapping per hospital
    HOSPITAL_ROUTERS = {
        "hq": {"edge": "r1_hq_edge", "core": "r2_hq_core", "switch": "sw_hq_access"},
        "diag": {"edge": "r4_diag_edge", "core": "r5_diag_core", "switch": "sw_diag_access"},
        "emer": {"edge": "r6_emer_edge", "core": "r7_emer_core", "switch": "sw_emer_access"},
        "tele": {"edge": "r9_tele_edge", "core": "r10_tele_core", "switch": "sw_tele_access"},
        "mat": {"edge": "r11_mat_edge", "core": "r12_mat_core", "switch": "sw_mat_access"},
        "child": {"edge": "r13_child_edge", "core": "r14_child_core", "switch": "sw_child_access"},
        "isp": {"edge": "r0_isp", "core": "r0_isp", "switch": "sw0_isp"}
    }

    # WAN edges connecting switch to routers
    WAN_EDGES = {
        "hq": ("e_sw0_r1", "e_r1_r2", "e_r2_swhq"),
        "diag": ("e_sw0_r4", "e_r4_r5", "e_r5_swdiag"),
        "emer": ("e_sw0_r6", "e_r6_r7", "e_r7_swemer"),
        "tele": ("e_sw0_r9", "e_r9_r10", "e_r10_swtele"),
        "mat": ("e_sw0_r11", "e_r11_r12", "e_r12_swmat"),
        "child": ("e_sw0_r13", "e_r13_r14", "e_r14_swchild"),
    }

    _auto_traffic_enabled: bool = True

    @classmethod
    def trace_packet(
        cls,
        db: Session,
        source_id: str,
        dest_id: str,
        protocol: str = "ICMP"
    ) -> SimulationFlow:
        source = db.query(DeviceModel).filter(DeviceModel.id == source_id).first()
        dest = db.query(DeviceModel).filter(DeviceModel.id == dest_id).first()

        if not source or not dest:
            raise ValueError(f"Invalid source ({source_id}) or destination ({dest_id}) device ID")

        src_hosp = source.hospital_id
        dst_hosp = dest.hospital_id
        flow_id = f"SIM-{uuid.uuid4().hex[:8].upper()}"
        now = datetime.utcnow()

        hops: List[SimulationHop] = []
        path_node_ids: List[str] = []
        path_edge_ids: List[str] = []

        is_acl_blocked = False
        acl_reason = ""

        # Check for ACL rules (Guest VLAN 50 or unprivileged access)
        if "guest" in source.id.lower() or "50" in source.id:
            if "srv_ftp" in dest.id or "srv_mail" in dest.id:
                is_acl_blocked = True
                acl_reason = "DENY tcp 10.0.0.0/24 -> 10.0.1.164 (Extended ACL 101: Guest Isolation Rule)"

        # --- Hop 1: Source Device ---
        hops.append(SimulationHop(
            hop_number=1,
            device_id=source.id,
            device_name=source.name,
            device_type=source.device_type,
            hospital_id=src_hosp,
            interface_in="Internal",
            interface_out="NIC-0/Ethernet",
            action="INGRESS",
            latency_ms=0.4,
            details=f"Packet generated by {source.name} ({source.ip_address}) for destination {dest.ip_address} via {protocol}"
        ))
        path_node_ids.append(source.id)

        # --- Intermediate Hops ---
        src_map = cls.HOSPITAL_ROUTERS.get(src_hosp, cls.HOSPITAL_ROUTERS["isp"])
        dst_map = cls.HOSPITAL_ROUTERS.get(dst_hosp, cls.HOSPITAL_ROUTERS["isp"])

        # Step 2: Local Access Switch (if source is not the switch itself)
        if source.id != src_map["switch"] and source.id != src_map["core"]:
            sw_dev = db.query(DeviceModel).filter(DeviceModel.id == src_map["switch"]).first()
            if sw_dev:
                hops.append(SimulationHop(
                    hop_number=len(hops) + 1,
                    device_id=sw_dev.id,
                    device_name=sw_dev.name,
                    device_type="SWITCH",
                    hospital_id=src_hosp,
                    interface_in="Fa0/Access",
                    interface_out="Gi0/1 (Trunk)",
                    action="VLAN_TAGGED",
                    latency_ms=0.6,
                    details=f"Layer 2 frame tagged with 802.1Q VLAN header and forwarded along access switch trunk"
                ))
                path_node_ids.append(sw_dev.id)

        # Step 3: Local Core Router (RoAS Gateway)
        if source.id != src_map["core"]:
            core_dev = db.query(DeviceModel).filter(DeviceModel.id == src_map["core"]).first()
            if core_dev:
                hops.append(SimulationHop(
                    hop_number=len(hops) + 1,
                    device_id=core_dev.id,
                    device_name=core_dev.name,
                    device_type="ROUTER",
                    hospital_id=src_hosp,
                    interface_in="Gi0/1.subif",
                    interface_out="Gi0/0",
                    action="ROUTED_EIGRP",
                    latency_ms=1.2,
                    details=f"Inter-VLAN default gateway lookup; forwarded via EIGRP AS 100 towards Edge Router"
                ))
                path_node_ids.append(core_dev.id)
                if src_hosp in cls.WAN_EDGES:
                    path_edge_ids.append(cls.WAN_EDGES[src_hosp][2])

        # If destinations are in DIFFERENT hospitals
        if src_hosp != dst_hosp:
            # Step 4: Source Edge Router (NAT / PAT Overload)
            edge_dev = db.query(DeviceModel).filter(DeviceModel.id == src_map["edge"]).first()
            if edge_dev:
                hops.append(SimulationHop(
                    hop_number=len(hops) + 1,
                    device_id=edge_dev.id,
                    device_name=edge_dev.name,
                    device_type="ROUTER",
                    hospital_id=src_hosp,
                    interface_in="Gi0/1",
                    interface_out="Gi0/0",
                    action="NAT_TRANSLATED",
                    latency_ms=1.8,
                    details=f"NAT Overload translation applied to public IP {edge_dev.ip_address}; routed to ISP aggregation switch"
                ))
                path_node_ids.append(edge_dev.id)
                if src_hosp in cls.WAN_EDGES:
                    path_edge_ids.append(cls.WAN_EDGES[src_hosp][1])

            # Step 5: ISP Switch
            sw0 = db.query(DeviceModel).filter(DeviceModel.id == "sw0_isp").first()
            if sw0:
                hops.append(SimulationHop(
                    hop_number=len(hops) + 1,
                    device_id=sw0.id,
                    device_name=sw0.name,
                    device_type="SWITCH",
                    hospital_id="isp",
                    interface_in="Fa0/BranchPort",
                    interface_out="Gi0/1",
                    action="TRUNK_FORWARDED",
                    latency_ms=0.8,
                    details="802.1Q WAN trunk aggregation switch multiplexes inter-hospital frames onto ISP Core trunk"
                ))
                path_node_ids.append("sw0_isp")
                path_edge_ids.append("e_r0_sw0")

            # Step 6: ISP Core Router (R0)
            r0 = db.query(DeviceModel).filter(DeviceModel.id == "r0_isp").first()
            if r0:
                hops.append(SimulationHop(
                    hop_number=len(hops) + 1,
                    device_id=r0.id,
                    device_name=r0.name,
                    device_type="ROUTER",
                    hospital_id="isp",
                    interface_in="Gi0/0.subif",
                    interface_out="Gi0/0.dst_subif",
                    action="ROUTED_EIGRP",
                    latency_ms=2.1,
                    details=f"ISP Core (R0) AS 100 routing lookup: destination network {dst_hosp.upper()} matched. Forwarding to destination Edge Router."
                ))
                path_node_ids.append("r0_isp")

            # Step 7: Destination Edge Router
            dst_edge = db.query(DeviceModel).filter(DeviceModel.id == dst_map["edge"]).first()
            if dst_edge:
                if dst_hosp in cls.WAN_EDGES:
                    path_edge_ids.append(cls.WAN_EDGES[dst_hosp][0])
                hops.append(SimulationHop(
                    hop_number=len(hops) + 1,
                    device_id=dst_edge.id,
                    device_name=dst_edge.name,
                    device_type="ROUTER",
                    hospital_id=dst_hosp,
                    interface_in="Gi0/0",
                    interface_out="Gi0/1",
                    action="ROUTED_EIGRP",
                    latency_ms=1.5,
                    details=f"Destination Edge {dst_edge.name} verified routing table; forwarded across point-to-point link to Core"
                ))
                path_node_ids.append(dst_edge.id)

        # Step 8: Destination Core Router
        dst_core = db.query(DeviceModel).filter(DeviceModel.id == dst_map["core"]).first()
        if dst_core and (len(hops) == 0 or hops[-1].device_id != dst_core.id):
            if dst_hosp in cls.WAN_EDGES:
                path_edge_ids.append(cls.WAN_EDGES[dst_hosp][1])
            hops.append(SimulationHop(
                hop_number=len(hops) + 1,
                device_id=dst_core.id,
                device_name=dst_core.name,
                device_type="ROUTER",
                hospital_id=dst_hosp,
                interface_in="Gi0/0",
                interface_out="Gi0/1.vlan",
                action="ACL_INSPECTED" if not is_acl_blocked else "DROPPED",
                latency_ms=1.1,
                details="Extended Access Control List (ACL) inspection passed" if not is_acl_blocked else f"PACKET DROPPED BY ACL: {acl_reason}"
            ))
            path_node_ids.append(dst_core.id)

        # If ACL blocked, terminate flow
        if is_acl_blocked:
            final_status = "DROPPED"
            summary_text = f"Packet DROPPED at {dst_core.name if dst_core else 'Core Router'}: {acl_reason}"
        else:
            # Step 9: Destination Access Switch (if dest is not the switch)
            if dest.id != dst_map["switch"]:
                dst_sw = db.query(DeviceModel).filter(DeviceModel.id == dst_map["switch"]).first()
                if dst_sw:
                    if dst_hosp in cls.WAN_EDGES:
                        path_edge_ids.append(cls.WAN_EDGES[dst_hosp][2])
                    hops.append(SimulationHop(
                        hop_number=len(hops) + 1,
                        device_id=dst_sw.id,
                        device_name=dst_sw.name,
                        device_type="SWITCH",
                        hospital_id=dst_hosp,
                        interface_in="Gi0/1 (Trunk)",
                        interface_out="FastEthernet/Access",
                        action="TRUNK_FORWARDED",
                        latency_ms=0.5,
                        details="Access switch unencapsulated 802.1Q header and delivered to target access port"
                    ))
                    path_node_ids.append(dst_sw.id)

            # Step 10: Final Destination Endpoint
            hops.append(SimulationHop(
                hop_number=len(hops) + 1,
                device_id=dest.id,
                device_name=dest.name,
                device_type=dest.device_type,
                hospital_id=dst_hosp,
                interface_in="FastEthernet/NIC",
                interface_out=None,
                action="DELIVERED",
                latency_ms=0.3,
                details=f"Packet successfully received by {dest.name} ({dest.ip_address}). {protocol} handshake acknowledged."
            ))
            path_node_ids.append(dest.id)
            final_status = "DELIVERED"
            summary_text = f"Successfully delivered {protocol} payload from {source.name} to {dest.name} across {len(hops)} hops ({sum(h.latency_ms for h in hops):.1f}ms)."

        total_latency = round(sum(h.latency_ms for h in hops), 2)

        flow = SimulationFlow(
            flow_id=flow_id,
            timestamp=now,
            source_device_id=source.id,
            source_device_name=source.name,
            source_ip=source.ip_address,
            source_hospital=src_hosp,
            dest_device_id=dest.id,
            dest_device_name=dest.name,
            dest_ip=dest.ip_address,
            dest_hospital=dst_hosp,
            protocol=protocol,
            status=final_status,
            total_latency_ms=total_latency,
            hops=hops,
            path_node_ids=list(dict.fromkeys(path_node_ids)),  # remove duplicates preserving order
            path_edge_ids=list(dict.fromkeys(path_edge_ids)),
            summary=summary_text
        )

        # Persist event log into SQLite
        event = EventLogModel(
            event_id=f"EVT-FLOW-{uuid.uuid4().hex[:6].upper()}",
            timestamp=now,
            category="DATA_TRANSFER",
            event_type="PACKET_FLOW_SIMULATION",
            severity="INFO" if final_status == "DELIVERED" else "WARNING",
            source="PACKET_TRACER",
            affected_device_id=source.id,
            hospital_id=src_hosp,
            interface_name=hops[0].interface_out if hops else "Gi0/0",
            previous_state="IDLE",
            new_state=final_status,
            description=summary_text,
            detection_method="SIMULATION_TRACER",
            verification_status="VERIFIED",
            metadata_json=json.dumps(flow.model_dump(mode="json"))
        )
        db.add(event)
        db.commit()

        return flow

    @classmethod
    async def broadcast_flow(cls, flow: SimulationFlow):
        """Broadcasts the simulation flow live over WebSockets to all connected clients."""
        await manager.broadcast({
            "type": "SIMULATION_FLOW_UPDATE",
            "timestamp": datetime.utcnow().isoformat(),
            "payload": {
                "flow": flow.model_dump(mode="json"),
                "events": [{
                    "id": random.randint(1000, 9999),
                    "event_id": flow.flow_id,
                    "timestamp": flow.timestamp.isoformat(),
                    "category": "DATA_TRANSFER",
                    "event_type": "PACKET_FLOW_SIMULATION",
                    "severity": "INFO" if flow.status == "DELIVERED" else "WARNING",
                    "source": "PACKET_TRACER",
                    "affected_device_id": flow.source_device_id,
                    "hospital_id": flow.source_hospital,
                    "description": flow.summary,
                    "detection_method": "SIMULATION_TRACER",
                    "verification_status": "VERIFIED",
                    "metadata": flow.model_dump(mode="json")
                }]
            }
        })
